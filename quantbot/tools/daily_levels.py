"""Today's predicted high / low from QuantBot's local model -> a ready-to-paste TradingView Pine indicator.

TradingView doesn't let Pine scripts fetch outside data, so this script does the fetching: it asks the running
QuantBot app (which asks your local model, once per day per symbol) and writes the levels into the indicator.
Run it each morning (or from Windows Task Scheduler), paste the result into TradingView's Pine Editor, and Save.

usage: python daily_levels.py [XAUUSD|US100|NQ ...] [--port 5173] [--out qb-daily-levels.pine] [--no-clipboard]
"""
import argparse, json, os, platform, subprocess, sys, urllib.request

def levels(port, symbol):
    url = f"http://127.0.0.1:{port}/api/levels?symbol={symbol}"
    try:
        with urllib.request.urlopen(url, timeout=600) as r:
            return json.load(r)
    except urllib.error.HTTPError as e:
        sys.exit(f"QuantBot answered {e.code} for {symbol}: {e.read().decode(errors='replace')[:300]}")
    except OSError as e:
        sys.exit(f"QuantBot isn't answering on port {port} ({e}). Open the QuantBot app first.")

def pine(data):
    rows = []
    for d in data:
        seen = {}
        for x in d["history"] + [d["today"]]:
            seen[x["day"]] = x
        for x in sorted(seen.values(), key=lambda x: x["day"]):
            rows.append((d["symbol"], int(x["day"].replace("-", "")), float(x["high"]), float(x["low"]), int(x.get("confidence") or 0)))
    syms = sorted({r[0] for r in rows})
    arr = lambda k: ", ".join(str(r[k]) if k else f'"{r[0]}"' for r in rows)
    newest = max(r[1] for r in rows)
    return f'''// Script: QB Daily High/Low (local model)
//@version=5
// Generated by QuantBot tools/daily_levels.py with levels up to {newest}. The predicted high / low for each day come from
// your local model through QuantBot; run the script again each day for new levels. Pine can't fetch them by itself.
indicator("QB Daily High/Low (local model)", overlay=true, max_lines_count=500, max_labels_count=500)
sym = input.string("{syms[0]}", "QuantBot symbol for this chart", options=[{", ".join(f'"{s}"' for s in syms)}])
colHi = input.color(color.new(#e5534b, 0), "Predicted high")
colLo = input.color(color.new(#3fb950, 0), "Predicted low")
showConf = input.bool(true, "Show confidence")
var syms = array.from({arr(0)})
var days = array.from({arr(1)})
var his = array.from({arr(2)})
var los = array.from({arr(3)})
var confs = array.from({arr(4)})
// New York trading day of this bar as yyyymmdd
nyDay = year(time, "America/New_York") * 10000 + month(time, "America/New_York") * 100 + dayofmonth(time, "America/New_York")
isNew = ta.change(nyDay) != 0
var line hiLine = na
var line loLine = na
if isNew
    for i = 0 to array.size(days) - 1
        if array.get(days, i) == nyDay and array.get(syms, i) == sym
            hiLine := line.new(bar_index, array.get(his, i), bar_index + 1, array.get(his, i), color=colHi, width=2, extend=extend.right)
            loLine := line.new(bar_index, array.get(los, i), bar_index + 1, array.get(los, i), color=colLo, width=2, extend=extend.right)
            line.set_extend(hiLine[1], extend.none)
            line.set_extend(loLine[1], extend.none)
            if showConf
                label.new(bar_index, array.get(his, i), "Model high " + str.tostring(array.get(his, i)) + " · " + str.tostring(array.get(confs, i)) + "%", color=color.new(colHi, 85), textcolor=colHi, style=label.style_label_down, size=size.small)
                label.new(bar_index, array.get(los, i), "Model low " + str.tostring(array.get(los, i)), color=color.new(colLo, 85), textcolor=colLo, style=label.style_label_up, size=size.small)
'''

def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("symbols", nargs="*", default=["XAUUSD", "US100"])
    ap.add_argument("--port", type=int, default=int(os.environ.get("QUANTBOT_PORT", 5173)))
    ap.add_argument("--out", default="qb-daily-levels.pine")
    ap.add_argument("--no-clipboard", action="store_true")
    a = ap.parse_args()
    data = []
    for s in a.symbols:
        d = levels(a.port, s.upper())
        t = d["today"]
        print(f"{d['symbol']} {t['day']}: high {t['high']}  low {t['low']}  confidence {t.get('confidence')}%  ({t.get('why', '')})")
        data.append(d)
    code = pine(data)
    with open(a.out, "w", encoding="utf-8") as f:
        f.write(code)
    print(f"Pine indicator written to {os.path.abspath(a.out)}")
    if not a.no_clipboard:
        cmd = {"Windows": ["clip"], "Darwin": ["pbcopy"]}.get(platform.system())
        if cmd:
            subprocess.run(cmd, input=code.encode("utf-16" if cmd == ["clip"] else "utf-8"), check=False)
            print("Copied: paste it into TradingView's Pine Editor and press Save (or Update on chart).")

if __name__ == "__main__":
    main()
